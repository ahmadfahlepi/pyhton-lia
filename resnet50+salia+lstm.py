import torch
import torch.nn as nn
import torch.nn.functional as F
from torchvision import models


# =========================================================
# 1. DBSA: DUAL-BRANCH SALIENT ATTENTION
# =========================================================
class DBSA(nn.Module):
    def __init__(self, channels=2048, reduction=16):
        super().__init__()

        reduced = channels // reduction

        # Cabang fitur pusat
        self.central_conv = nn.Sequential(
            nn.Conv2d(
                channels, reduced,
                kernel_size=3, padding=1
            ),
            nn.ReLU(inplace=True),
            nn.Conv2d(
                reduced, channels,
                kernel_size=3, padding=1
            ),
            nn.Sigmoid()
        )

        # Cabang perhatian spasial global
        self.global_attention = nn.Conv2d(
            channels, 1, kernel_size=1
        )

        # Proyeksi konteks global
        self.global_projection = nn.Conv2d(
            channels, channels, kernel_size=1
        )

        # Penggabungan kedua cabang
        self.gate = nn.Conv2d(
            channels * 2, channels, kernel_size=1
        )

        self.output_norm = nn.BatchNorm2d(channels)

    def forward(self, x):
        B, C, H, W = x.shape

        # Cabang pusat: fitur tengah sebagai petunjuk,
        # tetapi fitur asli seluruh area tetap dipertahankan.
        center = x[
            :,
            :,
            H // 4: max(H // 4 + 1, 3 * H // 4),
            W // 4: max(W // 4 + 1, 3 * W // 4)
        ]

        center_attention = self.central_conv(center)

        center_attention = F.interpolate(
            center_attention,
            size=(H, W),
            mode="bilinear",
            align_corners=False
        )

        central_features = x * center_attention

        # Perhatian global pada semua posisi spasial
        attention_logits = self.global_attention(x)
        attention_weights = attention_logits.flatten(2).softmax(
            dim=-1
        ).view(B, 1, H, W)

        global_context = (
            x * attention_weights
        ).sum(dim=(2, 3), keepdim=True)

        global_context = self.global_projection(global_context)

        # Konteks global digabungkan dengan fitur seluruh area
        global_features = x + global_context

        gate = torch.sigmoid(
            self.gate(
                torch.cat(
                    [central_features, global_features],
                    dim=1
                )
            )
        )

        output = (
            gate * central_features
            + (1.0 - gate) * global_features
        )

        # Residual menjaga informasi fitur awal
        return self.output_norm(output + x)


# =========================================================
# 2. LIA: LOCAL INTERACTION AGGREGATOR
# =========================================================
class LIA(nn.Module):
    def __init__(self, channels=2048, embed_dim=512):
        super().__init__()

        # Interaksi lokal antarf fitur berdekatan
        self.local_interaction = nn.Sequential(
            nn.Conv2d(
                channels, channels,
                kernel_size=3, padding=1,
                groups=channels, bias=False
            ),
            nn.BatchNorm2d(channels),
            nn.ReLU(inplace=True),
            nn.Conv2d(
                channels, embed_dim,
                kernel_size=1
            ),
            nn.ReLU(inplace=True)
        )

        # Agregasi spasial berurutan
        self.feature_lstm = nn.LSTM(
            input_size=embed_dim,
            hidden_size=embed_dim,
            batch_first=True
        )

        self.norm = nn.LayerNorm(embed_dim)

    def forward(self, x):
        x = self.local_interaction(x)

        # Urutan spasial konsisten: baris demi baris
        B, C, H, W = x.shape
        x = x.flatten(2).transpose(1, 2)

        features, _ = self.feature_lstm(x)

        return self.norm(features)


# =========================================================
# 3. VISUAL ATTENTION
# =========================================================
class VisualAttention(nn.Module):
    def __init__(self, feature_dim=512, hidden_dim=512):
        super().__init__()

        self.feature_layer = nn.Linear(
            feature_dim, hidden_dim
        )
        self.hidden_layer = nn.Linear(
            hidden_dim, hidden_dim
        )
        self.score = nn.Linear(hidden_dim, 1)

    def forward(self, features, hidden):
        visual = self.feature_layer(features)
        query = self.hidden_layer(hidden).unsqueeze(1)

        energy = torch.tanh(visual + query)
        scores = self.score(energy).squeeze(-1)

        weights = torch.softmax(scores, dim=1)

        context = torch.bmm(
            weights.unsqueeze(1), features
        ).squeeze(1)

        return context


# =========================================================
# 4. RESNET50 + DBSA + LIA + LSTM DECODER
# =========================================================
class SALIA_LSTM(nn.Module):
    def __init__(
        self,
        vocab_size,
        embed_dim=512,
        hidden_dim=512,
        pad_idx=0,
        pretrained=True,
        freeze_encoder=False
    ):
        super().__init__()

        self.pad_idx = pad_idx
        self.hidden_dim = hidden_dim
        self.embed_dim = embed_dim
        self.freeze_encoder = freeze_encoder

        # ResNet50 pretrained
        weights = (
            models.ResNet50_Weights.DEFAULT
            if pretrained else None
        )
        resnet = models.resnet50(weights=weights)

        # Mengambil feature map sebelum average pooling dan FC
        self.encoder = nn.Sequential(
            *list(resnet.children())[:-2]
        )

        if freeze_encoder:
            for parameter in self.encoder.parameters():
                parameter.requires_grad = False

        # Komponen SALIA
        self.dbsa = DBSA(channels=2048)
        self.lia = LIA(
            channels=2048,
            embed_dim=embed_dim
        )

        # Embedding teks
        self.embedding = nn.Embedding(
            vocab_size,
            embed_dim,
            padding_idx=pad_idx
        )

        # Attention visual
        self.attention = VisualAttention(
            feature_dim=embed_dim,
            hidden_dim=hidden_dim
        )

        # Inisialisasi hidden state dan cell state dari
        # ringkasan fitur visual
        self.init_hidden = nn.Sequential(
            nn.Linear(embed_dim, hidden_dim),
            nn.Tanh()
        )
        self.init_cell = nn.Sequential(
            nn.Linear(embed_dim, hidden_dim),
            nn.Tanh()
        )

        # Decoder menerima embedding kata + konteks visual
        self.decoder = nn.LSTMCell(
            embed_dim + embed_dim,
            hidden_dim
        )

        self.dropout = nn.Dropout(0.3)

        self.output_layer = nn.Linear(
            hidden_dim + embed_dim,
            vocab_size
        )

    def train(self, mode=True):
        super().train(mode)

        # Jika encoder dibekukan, BatchNorm encoder juga
        # tetap menggunakan statistik pretrained.
        if self.freeze_encoder:
            self.encoder.eval()

        return self

    def extract_features(self, images):
        features = self.encoder(images)
        features = self.dbsa(features)
        features = self.lia(features)

        return features

    def forward(self, images, captions):
        """
        images:
            [B, 3, 224, 224]

        captions:
            [B, T], berisi token input termasuk BOS.
            Biasanya dipanggil menggunakan captions[:, :-1].

        output:
            [B, T, vocab_size]

        Output memiliki panjang yang sama dengan captions,
        agar cocok dengan target captions[:, 1:].
        """

        visual_features = self.extract_features(images)

        # Ringkasan seluruh lokasi visual
        visual_summary = visual_features.mean(dim=1)

        # Inisialisasi state decoder berdasarkan gambar
        hidden = self.init_hidden(visual_summary)
        cell = self.init_cell(visual_summary)

        embedded = self.dropout(
            self.embedding(captions)
        )

        outputs = []

        # Satu prediksi untuk setiap token input
        for t in range(captions.size(1)):
            word = embedded[:, t, :]

            context = self.attention(
                visual_features, hidden
            )

            decoder_input = torch.cat(
                [word, context], dim=1
            )

            hidden, cell = self.decoder(
                decoder_input, (hidden, cell)
            )

            prediction = self.output_layer(
                self.dropout(
                    torch.cat([hidden, context], dim=1)
                )
            )

            outputs.append(prediction)

        return torch.stack(outputs, dim=1)


