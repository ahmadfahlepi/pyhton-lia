# ============================================================
# 2. NORMALISASI ID GAMBAR
# ============================================================

def normalize_id(value):
    if pd.isna(value):
        return ""

    value = str(value).strip()

    if re.fullmatch(r"\d+\.0", value):
        value = value[:-2]

    return value


# ============================================================
# 3. MENCARI GAMBAR BERDASARKAN ID
# ============================================================

def find_image(folder, image_id):
    if not image_id:
        return None

    # Cari berdasarkan ekstensi yang diketahui
    for ext in IMAGE_EXTENSIONS:
        path = os.path.join(folder, image_id + ext)

        if os.path.isfile(path):
            return path

    # Jika ekstensi atau huruf kapital berbeda
    target = image_id.lower()

    for filename in os.listdir(folder):
        stem, ext = os.path.splitext(filename)

        if (
            stem.lower() == target
            and ext.lower() in IMAGE_EXTENSIONS
        ):
            return os.path.join(folder, filename)

    return None


