# 3. HITUNG LOSS DAN TOKEN ACCURACY
# ============================================================

def calculate_metrics(outputs, targets, criterion, pad_idx):
    """
    outputs: [B, T, V]
    targets: [B, T]

    Accuracy dihitung berdasarkan token yang bukan PAD.
    """

    if outputs.ndim != 3:
        raise ValueError(
            f"Output harus [B,T,V], diperoleh {tuple(outputs.shape)}"
        )

    if targets.ndim != 2:
        raise ValueError(
            f"Target harus [B,T], diperoleh {tuple(targets.shape)}"
        )

    if outputs.shape[:2] != targets.shape:
        raise ValueError(
            f"Panjang output dan target tidak cocok: "
            f"{tuple(outputs.shape)} vs {tuple(targets.shape)}"
        )

    loss = criterion(
        outputs.reshape(-1, outputs.size(-1)),
        targets.reshape(-1)
    )

    predictions = outputs.argmax(dim=-1)

    valid_mask = targets.ne(pad_idx)
    correct_mask = predictions.eq(targets) & valid_mask

    correct_tokens = correct_mask.sum().item()
    total_tokens = valid_mask.sum().item()

    return loss, correct_tokens, total_tokens


