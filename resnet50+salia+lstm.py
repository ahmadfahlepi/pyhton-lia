def validate_vocabulary(word2idx):
    required_tokens = [PAD, UNK, BOS, EOS]

    for token in required_tokens:
        if token not in word2idx:
            raise ValueError(
                f"Vocabulary tidak memiliki token {token}."
            )

    # Pastikan indeks unik
    if len(set(word2idx.values())) != len(word2idx):
        raise ValueError(
            "Terdapat indeks vocabulary yang duplikat."
        )

    return True


