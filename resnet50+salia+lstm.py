# 5. COLLATE FUNCTION
# ============================================================

def make_collate_fn(word2idx):
    pad_idx = word2idx[PAD]

    def collate_fn(batch):
        images, captions = zip(*batch)

        images = torch.stack(images)

        captions = pad_sequence(
            captions,
            batch_first=True,
            padding_value=pad_idx
        )

        return images, captions

    return collate_fn

import re
from collections import Counter

# ============================================================
# 1. TOKEN KHUSUS
# ============================================================

PAD = "<pad>"
UNK = "<unk>"
BOS = "<bos>"
EOS = "<eos>"

SPECIAL_TOKENS = [PAD, UNK, BOS, EOS]

# Maksimal 40 token, termasuk BOS dan EOS
MAX_LEN = 40


# ============================================================
# 2. TOKENISASI TEKS
# ============================================================

def tokenize(text):
    """
    Mengubah teks menjadi token huruf kecil.
    Tanda baca dan simbol menjadi pemisah token.
    """

    if text is None:
        return []

    text = str(text).lower().strip()

    if not text or text == "nan":
        return []

    return re.findall(r"\b\w+\b", text, flags=re.UNICODE)


# ============================================================
# 3. MEMBANGUN VOCABULARY
# ============================================================

def build_vocabulary(texts):
    """
    Vocabulary hanya dibuat dari description data training
    pada fold yang sedang diproses.
    """

    counter = Counter()

    for text in texts:
        counter.update(tokenize(text))

    # Token khusus selalu berada di indeks awal
    words = SPECIAL_TOKENS + sorted(
        word
        for word in counter
        if word not in SPECIAL_TOKENS
    )

    word2idx = {
        word: idx
        for idx, word in enumerate(words)
    }

    return word2idx


# ============================================================
# 4. ENCODING CAPTION
# ============================================================

def encode_caption(text, word2idx):
    """
    Urutan caption:
    BOS + token teks + EOS

    Panjang maksimal termasuk BOS dan EOS adalah MAX_LEN.
    """

    required_tokens = [PAD, UNK, BOS, EOS]

    for token in required_tokens:
        if token not in word2idx:
            raise KeyError(
                f"Token khusus {token} tidak ada di vocabulary."
            )

    tokens = tokenize(text)[:MAX_LEN - 2]

    ids = [word2idx[BOS]]

    ids.extend(
        word2idx.get(token, word2idx[UNK])
        for token in tokens
    )

    ids.append(word2idx[EOS])

    return ids


# ============================================================
