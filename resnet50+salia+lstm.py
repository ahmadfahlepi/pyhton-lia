# 4. TRAINING SATU EPOCH
# ============================================================

def train_one_epoch(
    model, loader, optimizer, criterion, pad_idx
):
    model.train()

    total_loss = 0.0
    total_correct = 0
    total_tokens = 0

    for images, captions in loader:
        images = images.to(
            DEVICE, non_blocking=True
        )
        captions = captions.to(
            DEVICE, non_blocking=True
        )

        # Teacher forcing
        decoder_input = captions[:, :-1]
        targets = captions[:, 1:]

        optimizer.zero_grad(set_to_none=True)

        outputs = model(images, decoder_input)

        loss, correct, tokens = calculate_metrics(
            outputs, targets, criterion, pad_idx
        )

        loss.backward()

        torch.nn.utils.clip_grad_norm_(
            model.parameters(), max_norm=1.0
        )

        optimizer.step()

        total_loss += loss.item() * tokens
        total_correct += correct
        total_tokens += tokens

    if total_tokens == 0:
        raise RuntimeError(
            "Tidak ada token training yang valid."
        )

    epoch_loss = total_loss / total_tokens
    epoch_accuracy = 100.0 * total_correct / total_tokens

    return epoch_loss, epoch_accuracy


# ============================================================
# 5. VALIDATION SATU EPOCH
# ============================================================

def validate_one_epoch(
    model, loader, criterion, pad_idx
):
    model.eval()

    total_loss = 0.0
    total_correct = 0
    total_tokens = 0

    with torch.no_grad():
        for images, captions in loader:
            images = images.to(
                DEVICE, non_blocking=True
            )
            captions = captions.to(
                DEVICE, non_blocking=True
            )

            decoder_input = captions[:, :-1]
            targets = captions[:, 1:]

            outputs = model(images, decoder_input)

            loss, correct, tokens = calculate_metrics(
                outputs, targets, criterion, pad_idx
            )

            total_loss += loss.item() * tokens
            total_correct += correct
            total_tokens += tokens

    if total_tokens == 0:
        raise RuntimeError(
            "Tidak ada token validation yang valid."
        )

    epoch_loss = total_loss / total_tokens
    epoch_accuracy = 100.0 * total_correct / total_tokens

    return epoch_loss, epoch_accuracy


