class CaptionDataset(Dataset):
    def __init__(
        self,
        csv_path,
        image_folder,
        word2idx,
        is_training=False,
        transform=None
    ):
        self.samples = []
        self.word2idx = word2idx
        self.transform = transform or image_transform
        self.is_training = is_training

        df = pd.read_csv(csv_path)

        required_columns = {"id", "description"}
        missing_columns = required_columns - set(df.columns)

        if missing_columns:
            raise KeyError(
                f"Kolom CSV tidak ditemukan: {missing_columns}"
            )

        # Daftar file augmentasi diindeks satu kali
        # agar tidak memindai folder untuk setiap baris CSV.
        augmented_by_stem = {}

        if is_training:
            for filename in os.listdir(image_folder):
                stem, ext = os.path.splitext(filename)

                if ext.lower() not in IMAGE_EXTENSIONS:
                    continue

                match = re.match(r"^(.+)_aug.*$", stem)

                if match:
                    original_stem = match.group(1)
                    augmented_by_stem.setdefault(
                        original_stem, []
                    ).append(
                        os.path.join(image_folder, filename)
                    )

        skipped_empty = 0
        skipped_missing = 0
        skipped_corrupt = 0

        for _, row in df.iterrows():

            image_id = normalize_id(row["id"])
            raw_description = row["description"]

            # Abaikan description kosong atau NaN
            if pd.isna(raw_description):
                skipped_empty += 1
                continue

            description = str(raw_description).strip()

            if not description:
                skipped_empty += 1
                continue

            original = find_image(image_folder, image_id)

            if original is None:
                skipped_missing += 1
                continue

            # Validasi gambar asli agar gambar rusak dilewati
            try:
                with Image.open(original) as img:
                    img.verify()

                with Image.open(original) as img:
                    img.convert("RGB").load()

            except (
                UnidentifiedImageError,
                OSError,
                ValueError
            ):
                skipped_corrupt += 1
                continue

            # Tambahkan gambar asli
            self.samples.append((original, description))

            # Tambahkan gambar augmentasi hanya untuk training
            if is_training:
                stem = os.path.splitext(
                    os.path.basename(original)
                )[0]

                for aug_path in augmented_by_stem.get(stem, []):

                    try:
                        with Image.open(aug_path) as img:
                            img.verify()

                        with Image.open(aug_path) as img:
                            img.convert("RGB").load()

                    except (
                        UnidentifiedImageError,
                        OSError,
                        ValueError
                    ):
                        skipped_corrupt += 1
                        continue

                    self.samples.append(
                        (aug_path, description)
                    )

        print(f"CSV: {csv_path}")
        print(f"Training: {self.is_training}")
        print(f"Jumlah sampel valid: {len(self.samples)}")
        print(f"Description kosong: {skipped_empty}")
        print(f"Gambar tidak ditemukan: {skipped_missing}")
        print(f"Gambar rusak dilewati: {skipped_corrupt}")

    def __len__(self):
        return len(self.samples)

    def __getitem__(self, idx):
        image_path, description = self.samples[idx]

        # Buka gambar dan ubah menjadi RGB
        with Image.open(image_path) as img:
            image = img.convert("RGB")
            image = self.transform(image)

        # Tokenisasi menggunakan fungsi tokenize yang sudah ada
        tokens = tokenize(description)[:MAX_LEN - 2]

        # Urutan: BOS + token caption + EOS
        caption_ids = [self.word2idx[BOS]]

        caption_ids.extend(
            self.word2idx.get(token, self.word2idx[UNK])
            for token in tokens
        )

        caption_ids.append(self.word2idx[EOS])

        caption = torch.tensor(
            caption_ids,
            dtype=torch.long
        )

        return image, caption


